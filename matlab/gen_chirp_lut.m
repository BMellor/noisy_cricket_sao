% gen_chirp_lut.m  -  NoisyCricket chirp LUT generator (MATLAB / Octave, no toolboxes)
%
% Generates one cricket chirp as 8-bit unsigned PWM samples centred on 128,
% for table playback only (no on-the-fly MCU synthesis).
%
% The chirp is a fundamental linear sweep f0 -> f1 under a half-sine
% envelope, plus up to three overtones. Each overtone sweeps the same
% shape (same rate, same duration) shifted by a fixed Hz offset, and is
% scaled by a relative amplitude before being summed with the fundamental.
% All math is plain double-precision floating point; the sum is normalised
% to the requested peak deviation and quantised to 8 bits only at the very
% end.
%
% Outputs (written to out_dir):
%   chirp_lut.h         C array + constants for the MCU
%   chirp_lut_*.png     plots (if save_png)
%
% Usage: edit the configuration block below and run.

clear; close all; clc;

%% ---------------- configuration ----------------
fs_option  = 2;        % 1 = 46875 Hz (24 MHz/512), 2 = 23437.5 Hz (24 MHz/1024)
f0         = 3500;     % fundamental sweep start (Hz)
f1         = 4500;     % fundamental sweep end (Hz); f1 < f0 gives a down-sweep
T_ms       = 30;       % chirp length (ms)
amp        = 127;      % peak deviation from 128 after summing all partials, 1..127

overtone_offset_hz = [150, 320, 500];   % Hz, added to f0 and f1 for each overtone
overtone_amp       = [0.5, 0.35, 0.2];  % relative amplitude, each vs. the fundamental

out_dir    = '.';
out_name   = 'chirp_lut.h';
make_plots = true;
save_png   = true;
%% ------------------------------------------------

if numel(overtone_offset_hz) ~= numel(overtone_amp)
    error('overtone_offset_hz and overtone_amp must be the same length');
end

fs_list = [46875, 23437.5];
fs = fs_list(fs_option);
N  = round(T_ms * 1e-3 * fs);          % samples in the chirp
T  = N / fs;                           % actual chirp length (s)
n  = 0:N-1;
t  = n / fs;
k  = (f1 - f0) / T;                    % sweep rate, shared by all partials

% ---- envelope: half sine, sampled at bin centres ----
envelope = sin(pi * (n + 0.5) / N);

% ---- fundamental + overtones, each its own frequency-shifted sweep ----
carrier = sin(2*pi*(f0*t + 0.5*k*t.^2));           % fundamental, weight 1
for i = 1:numel(overtone_offset_hz)
    fo0 = f0 + overtone_offset_hz(i);
    carrier = carrier + overtone_amp(i) * sin(2*pi*(fo0*t + 0.5*k*t.^2));
end

raw = envelope .* carrier;

% ---- scale to the requested peak and quantise to 8 bits ----
scale   = amp / max(abs(raw));
y_ideal = 128 + scale * raw;                        % pre-quantisation reference
y       = 128 + round(scale * raw);
y       = min(255, max(0, y));

% ---- report ----
fprintf('\nChirp: %.0f -> %.0f Hz, %d samples @ %.4f kHz = %.3f ms\n', ...
        f0, f1, N, fs/1e3, T*1e3);
fprintf('Overtones (Hz offset / relative amp): ');
fprintf('%.0f/%.2f  ', [overtone_offset_hz; overtone_amp]);
fprintf('\n');
e = y - y_ideal;
fprintf('Quantisation error vs. scaled float: %.3f rms / %.3f max LSB\n', ...
        sqrt(mean(e.^2)), max(abs(e)));
fprintf('Headroom used: peak |raw| scaled to %d of 127\n', amp);
fprintf('Playback table: %d bytes\n\n', N);

% ---- C output ----
fid = fopen(fullfile(out_dir, out_name), 'w');
fprintf(fid, '/* Generated by gen_chirp_lut.m - do not edit.\n');
fprintf(fid, ' * Fundamental %.0f -> %.0f Hz sweep, half-sine envelope, %.3f ms, fs = %.4f Hz, %d samples.\n', f0, f1, T*1e3, fs, N);
fprintf(fid, ' * Overtones (Hz offset / relative amp): ');
for i = 1:numel(overtone_offset_hz)
    fprintf(fid, '%.0f/%.2f ', overtone_offset_hz(i), overtone_amp(i));
end
fprintf(fid, '\n');
fprintf(fid, ' * amp = %d (peak deviation from 128). Table playback only, no on-chip synthesis.\n', amp);
fprintf(fid, ' */\n#include <stdint.h>\n\n');
fprintf(fid, '#define CHIRP_FS_HZ        %.4f\n', fs);
fprintf(fid, '#define CHIRP_LEN          %d\n\n', N);

fprintf(fid, 'static const uint8_t chirp_lut[CHIRP_LEN] = {\n');
for i = 1:N
    if mod(i-1, 16) == 0, fprintf(fid, '    '); end
    fprintf(fid, '%d,', y(i));
    if mod(i, 16) == 0 || i == N, fprintf(fid, '\n'); else fprintf(fid, ' '); end
end
fprintf(fid, '};\n');
fclose(fid);
fprintf('Wrote %s\n', fullfile(out_dir, out_name));

% ---- plots ----
if make_plots
    if save_png, set(0, 'DefaultFigureVisible', 'off'); end

    f1h = figure('Position', [50 50 1000 800]);
    subplot(3,1,1);
    plot(t*1e3, y, '.-', t*1e3, y_ideal, '-'); grid on;
    xlabel('ms'); ylabel('PWM value'); legend('quantised 8-bit', 'scaled float');
    title(sprintf('Chirp %.0f-%.0f Hz + %d overtones, %d samples @ %.3f kHz', ...
          f0, f1, numel(overtone_offset_hz), N, fs/1e3));
    subplot(3,1,2);
    plot(t*1e3, e, '.-'); grid on; xlabel('ms'); ylabel('LSB');
    title(sprintf('Quantisation error (rms %.3f, max %.3f LSB)', sqrt(mean(e.^2)), max(abs(e))));
    subplot(3,1,3);
    zi = 1:min(N, round(1.5e-3*fs)); zj = max(1,N-round(1.5e-3*fs)):N;
    plot(t(zi)*1e3, y(zi), '.-', t(zi)*1e3, y_ideal(zi), '-'); grid on;
    xlabel('ms'); ylabel('PWM value'); title('Zoom: first 1.5 ms (low envelope)');
    if save_png, print(f1h, fullfile(out_dir, 'chirp_lut_wave.png'), '-dpng', '-r90'); end

    % spectrogram (own STFT, no toolbox)
    W = 128; H = 8; win = 0.5 - 0.5*cos(2*pi*(0:W-1)/W);
    nfr = floor((N - W) / H) + 1;
    S = zeros(W/2+1, nfr);
    for i = 1:nfr
        seg = (y((i-1)*H+1 : (i-1)*H+W) - 128) .* win;
        X = abs(fft(seg));
        S(:, i) = X(1:W/2+1);
    end
    fax = (0:W/2) * fs / W;
    tax = ((0:nfr-1)*H + W/2) / fs * 1e3;

    f2h = figure('Position', [50 50 1000 700]);
    subplot(2,1,1);
    imagesc(tax, fax/1e3, 20*log10(S/max(S(:)) + 1e-6), [-60 0]); axis xy; colorbar;
    ylim([2 6]); xlabel('ms'); ylabel('kHz'); title('Spectrogram of quantised chirp (dB)');
    hold on; plot(t*1e3, (f0 + (f1-f0)*(n+0.5)/N)/1e3, 'w--'); hold off;
    subplot(2,1,2);
    L = 2^nextpow2(8*N);
    Y = abs(fft((y - 128) .* (0.5 - 0.5*cos(2*pi*(0:N-1)/N)), L));
    Yi = abs(fft((y_ideal - 128) .* (0.5 - 0.5*cos(2*pi*(0:N-1)/N)), L));
    fa = (0:L/2) * fs / L;
    plot(fa/1e3, 20*log10(Y(1:L/2+1)/max(Y) + 1e-9), fa/1e3, 20*log10(Yi(1:L/2+1)/max(Yi) + 1e-9));
    grid on; xlim([0 fs/2e3]); ylim([-100 5]); xlabel('kHz'); ylabel('dB');
    legend('quantised', 'scaled float'); title('Spectrum (Hann window)');
    if save_png, print(f2h, fullfile(out_dir, 'chirp_lut_spec.png'), '-dpng', '-r90'); end
end
