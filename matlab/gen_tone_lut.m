% gen_tone_lut.m - NoisyCricket beep waveform (MATLAB / Octave, no toolboxes)
%
% One cycle of a soft-clipped sine, tanh(g*sin)/tanh(g), as signed 8-bit samples.
% g sets the timbre: ~0.5 is close to a pure sine, ~5 is close to a square wave.
% Writes ../firmware/src/tone_lut.h (played by a phase accumulator in audio.c).

clear; clc;

g        = 2.5;    % soft-clip drive
N        = 256;    % entries per cycle (indexed by the top 8 bits of the phase)
out_file = fullfile('..', 'firmware', 'src', 'tone_lut.h');

x = sin(2*pi*(0:N-1)/N);
y = round(127 * tanh(g*x) / tanh(g));

% harmonic content relative to the fundamental (odd harmonics only, by symmetry)
Y = abs(fft(y));
fprintf('g = %.2f: 3rd %.1f dB, 5th %.1f dB, 7th %.1f dB\n', g, ...
        20*log10(Y(4)/Y(2)), 20*log10(Y(6)/Y(2)), 20*log10(Y(8)/Y(2)));

fid = fopen(out_file, 'w');
fprintf(fid, '/* Generated by matlab/gen_tone_lut.m - do not edit.\n');
fprintf(fid, ' * One cycle of tanh(%.2f*sin)/tanh(%.2f), signed 8-bit, %d entries. */\n', g, g, N);
fprintf(fid, '#include <stdint.h>\n\n#define TONE_LUT_LEN %d\n\n', N);
fprintf(fid, 'static const int8_t tone_lut[TONE_LUT_LEN] = {\n');
for i = 1:N
  if mod(i-1, 16) == 0, fprintf(fid, '    '); end
  fprintf(fid, '%d,', y(i));
  if mod(i, 16) == 0 || i == N, fprintf(fid, '\n'); else fprintf(fid, ' '); end
end
fprintf(fid, '};\n');
fclose(fid);
fprintf('Wrote %s\n', out_file);
